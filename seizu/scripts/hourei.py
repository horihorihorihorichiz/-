def tier(y0, label, col, note, rows):
    s.rect(70, y0, 84, 22, fill=col, stroke='none', rx=4)
    s.text(112, y0 + 15, label, size=11.5, fill='#fff', weight='700')
    s.text(164, y0 + 15, note, size=11, anchor='start', fill='#555')
    for j, (art, name) in enumerate(rows):
        yy = y0 + 34 + j * 17
        s.rect(78, yy - 11, 116, 15, fill='#fff', stroke='#ccc',
               stroke_width=0.8, rx=2)
        s.text(84, yy, art, size=10, anchor='start', weight='700', fill=col)
        s.text(206, yy, name, size=10.5, anchor='start', fill='#333')
    return y0 + 34 + len(rows) * 17


