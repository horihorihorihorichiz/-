# -*- coding: utf-8 -*-
"""数値の考え方。すべての数字が910から出てくることを示す地図。"""
import os
from svgkit import Svg

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'figures')
W, H = 700, 1268
INK, RED, BLUE, GREEN = '#111', '#c0392b', '#2f7fd0', '#2f8f6a'

s = Svg(W, H)
s.text(W / 2.0, 32, '数字は、ぜんぶ 910 から出てくる', size=21, weight='700')
s.text(W / 2.0, 55, '910mm＝畳の短いほうの長さ。日本の木造はこれの倍数でできている',
       size=11.5, fill='#666')

# ---- 中心の910 ----
s.rect(W / 2.0 - 74, 76, 148, 52, fill='#fdecea', stroke=RED,
       stroke_width=1.8, rx=8)
s.text(W / 2.0, 100, '910', size=26, weight='800', fill=RED)
s.text(W / 2.0, 118, '1マス', size=11, fill=RED)

s.text(W / 2.0, 150, '↓　まず、よこの長さがぜんぶ決まる', size=11.5,
       fill='#666')

BASE = [('455', '半マス'), ('910', '1マス'), ('1,820', '2マス＝1間'),
        ('2,730', '3マス'), ('3,640', '4マス＝2間'), ('7,280', '8マス')]
bw = (W - 96) / len(BASE)
for i, (v, m) in enumerate(BASE):
    x = 48 + i * bw
    s.rect(x + 3, 162, bw - 6, 44, fill='#fff', stroke='#bbb',
           stroke_width=1.0, rx=5)
    s.text(x + bw / 2.0, 182, v, size=14, weight='700')
    s.text(x + bw / 2.0, 198, m, size=9.5, fill='#666')


def block(y0, color, title, rows, note=''):
    """高さは中身から決める。次のブロックの上端を返す。"""
    y1 = y0 + 48 + len(rows) * 24 + (26 if note else 8)
    s.rect(40, y0, W - 80, y1 - y0, fill='#fbfaf8', stroke=color,
           stroke_width=1.4, rx=8)
    s.rect(40, y0, 6, y1 - y0, fill=color, rx=0)
    s.text(62, y0 + 24, title, size=14.5, anchor='start', weight='700')
    for i, (a, b, c) in enumerate(rows):
        yy = y0 + 48 + i * 24
        s.text(72, yy, a, size=12, anchor='start', weight='700')
        s.text(240, yy, b, size=12, anchor='start', fill=RED, weight='700')
        s.text(370, yy, c, size=11, anchor='start', fill='#555')
    if note:
        s.text(72, y1 - 12, note, size=10.5, anchor='start', fill='#777')
    return y1 + 12


y = block(226, GREEN, '① 部屋の広さ', [
    ('1マス', '0.8281㎡', '0.91 × 0.91'),
    ('6帖の和室', '9.93㎡', '12マス（3マス×4マス）'),
    ('8帖', '13.24㎡', '16マス（4マス×4マス）'),
    ('この建物1階', '66.24㎡', '8マス×10マス ＝ 80マス'),
], '※ 小数点以下第3位以下は切り捨て。7.28×9.10＝66.248 → 66.24')

y = block(y, BLUE, '② 高さ', [
    ('1FL（1階の床）', 'GL＋550', '基礎371＋パッキン20＋土台120＋合板24＋床15'),
    ('階高（1階）', '3,100', '店舗は天井を高く'),
    ('階高（2階）', '2,900', '住宅の標準'),
    ('階高（3階）', '2,800', '同上'),
    ('軒高', 'GL＋9,350', '550＋3,100＋2,900＋2,800'),
    ('最高の高さ', 'GL＋10,806', '9,350＋1,456（屋根の三角）'),
], '※ 屋根の1,456は 3,640×0.4。4寸勾配＝よこ10進むとたて4上がる')

y = block(y, '#c9762f', '③ 部材の太さ', [
    ('柱（通し柱・管柱）', '120×120', 'ぜんぶ同じ'),
    ('梁の幅', '120', '柱に合わせる。全部そろえる'),
    ('梁のせい（1,820）', '180', 'スパンが短いので細くてよい'),
    ('梁のせい（2,730）', '240', ''),
    ('梁のせい（3,640）', '300', 'スパンが長いほど背を高く'),
    ('火打梁・母屋', '90×90', 'ここだけ90'),
], '※ 上に柱が乗ったら1寸（30mm）増し')

y = block(y, '#8b62b5', '④ 階段', [
    ('段数', '15段', '3,100 ÷ 220 ＝ 14.09 → 15段'),
    ('蹴上（1段の高さ）', '206.7', '3,100 ÷ 15。220以下ならOK'),
    ('踏面（1段の奥行）', '227.5', '910 ÷ 4。210以上ならOK'),
    ('階段室の大きさ', '1,820×3,640', '2マス×4マス'),
], '※ 蹴上は「上限以下」、踏面は「下限以上」。向きが逆なので注意')

y = block(y, '#555', '⑤ 紙の上の長さ（1／100）', [
    ('910（1マス）', '9.1mm', '方眼2マスぶん'),
    ('1,820', '18.2mm', '方眼4マスぶん'),
    ('7,280（建物の幅）', '72.8mm', '約7cm'),
    ('9,100（建物の奥行）', '91mm', '約9cm'),
], '※ 答案用紙の方眼は4.55mm＝455mm。2マス数えれば910')

s.save(os.path.join(OUT, 'suuji.svg'))
print('wrote suuji.svg')
